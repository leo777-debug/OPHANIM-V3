import { readdirSync, readFileSync, writeFileSync, existsSync } from 'node:fs';
import { resolve, relative, dirname } from 'node:path';
import ts from 'typescript';

const root = resolve(import.meta.dirname, '..');
const walk = (path) => readdirSync(path, { withFileTypes: true }).flatMap((entry) => {
  const target = resolve(path, entry.name);
  return entry.isDirectory() ? walk(target) : [target];
});
const files = walk(resolve(root, 'src'));
const parsed = new Map();
function inspect(path) {
  if (parsed.has(path)) return parsed.get(path);
  const source = readFileSync(path, 'utf8');
  const tree = ts.createSourceFile(path, source, ts.ScriptTarget.Latest, true);
  const imports = [];
  for (const node of tree.statements) {
    if (!ts.isImportDeclaration(node) || !ts.isStringLiteral(node.moduleSpecifier)) continue;
    const spec = node.moduleSpecifier.text;
    const base = spec.startsWith('@/') ? resolve(root, 'src', spec.slice(2))
      : spec.startsWith('.') ? resolve(dirname(path), spec) : null;
    if (!base) continue;
    const target = [base, `${base}.ts`, `${base}.tsx`, resolve(base, 'index.ts'), resolve(base, 'index.tsx')]
      .find((candidate) => files.includes(candidate));
    if (target) imports.push(target);
  }
  const result = { source, imports };
  parsed.set(path, result);
  return result;
}
function closure(path, seen = new Set()) {
  if (seen.has(path)) return seen;
  seen.add(path);
  for (const imported of inspect(path).imports) closure(imported, seen);
  return seen;
}
const rows = files.filter((file) => /[\\/](page\.tsx|route\.ts)$/.test(file)).map((file) => {
  const path = relative(root, file).replaceAll('\\', '/');
  const url = '/' + path.replace(/^src\/app\//, '').replace(/\/(page\.tsx|route\.ts)$/, '')
    .replace(/^(page\.tsx|route\.ts)$/, '').split('/').filter((part) => !/^\(.*\)$/.test(part)).join('/');
  const source = inspect(file).source;
  const dependencies = [...closure(file)];
  const text = dependencies.map((item) => inspect(item).source).join('\n');
  const api = file.endsWith('route.ts');
  const methods = api ? [...source.matchAll(/export\s+(?:async\s+)?function\s+(GET|POST|PUT|PATCH|DELETE|HEAD|OPTIONS)\b/g)].map((match) => match[1]).join(', ') : 'page';
  const session = /await\s+(?:requireAuthenticatedActor|getAuthenticatedActor|requestContext|authorizeAiRequest)\s*\(/.test(source);
  const auth = session ? (/requestContext/.test(source) ? 'Verify session (anonymous + optional login; AI needs login)' : /authorizeAiRequest/.test(source) ? 'Login + same-origin AI gate' : /requireAuthenticatedActor/.test(source) ? 'Login gate; inspect per-method permissions' : 'Optional actor; review method policy')
    : /CRON_SECRET|cronAuthorized|requireCron|isCronAuthorized|verifyCronSecret/.test(text) ? 'Cron secret / manual review'
    : /verifySignature|verifyWebhook|WEBHOOK_SECRET|SDK_API_KEY/.test(text) ? 'Signature/key / manual review'
    : api ? 'No direct login gate; review public policy' : 'UI shell; underlying API owns authorization';
  const external = /\bfetch\s*\(|new WebSocket\(|createGeminiClient|new Resend\(/.test(text);
  const ai = /generateWithRouting|generateContent|openAiCompatibleProvider|summarizeWithOptionalAi|parseWithOptionalAi|embeddingConfig|generateEmbedding/.test(text);
  return { url, methods, auth, external, ai, file: path };
}).sort((a, b) => a.url.localeCompare(b.url));
const escape = (value) => String(value).replaceAll('|', '\\|');
const table = (items) => ['| Route | Methods | Auth policy (static) | External reachable | AI reachable | Source |', '| --- | --- | --- | --- | --- | --- |',
  ...items.map((item) => `| ${[item.url, item.methods, item.auth, item.external ? 'yes' : 'not detected', item.ai ? 'yes' : 'not detected', item.file].map(escape).join(' | ')} |`)].join('\n');
writeFileSync(resolve(root, 'STRESS_TEST/APP_MAP.md'), `# Ophanim App Map\n\nGenerated by \`node STRESS_TEST/inventory.mjs\`. Includes every page.tsx and route.ts under src/app. Static import traversal detects reachable external and AI code, not proof that a request invokes it. Per-method runtime auth and tenant tests remain required. Layout/proxy authorization and dynamic imports require manual review. No endpoint was called to generate this inventory.\n\n## Pages\n\n${table(rows.filter((item) => item.methods === 'page'))}\n\n## API Routes\n\n${table(rows.filter((item) => item.methods !== 'page'))}\n`);
console.log(`Inventoried ${rows.length} pages/routes without making network requests.`);
if (existsSync(resolve(root, 'STRESS_TEST/lint-baseline.json'))) {
  const lint = JSON.parse(readFileSync(resolve(root, 'STRESS_TEST/lint-baseline.json'), 'utf8'));
  console.log(JSON.stringify({ lintFiles: lint.length, errors: lint.reduce((sum, item) => sum + item.errorCount, 0), warnings: lint.reduce((sum, item) => sum + item.warningCount, 0) }));
}
